#!/usr/bin/env python3
"""Scene-2's exports (STL/OBJ/DAE) are untextured and only hold the 107 m girder bridge plus
a generic SketchUp "Location Terrain" slab that has nothing to do with it. The .skp preview
shows the bridge crossing open water, so this rebuilds that setting around the bridge and
splits the bridge into per-component parts (see BRIDGE_PARTS_SPEC.md):

  bridge  : Scene-2_structure.stl, classified per triangle (deck, girders, bearings, pier caps,
            columns, footings, abutments, railings), one OBJ per instance, numbered along +Y
  river   : water surface z=0 running along X under the bridge, bed z=-1 (pier footings sit on it)
  banks   : grass land z=0.6 up to the abutment footings, sloping down into the river
  approach: road embankments filled right up to the abutment back walls (no voids under the
            deck overhang), level 40 m past the deck end, then ramping down to the land;
            their river-facing ends are concrete wingwalls, merged into the abutment parts

Textures come out of Scene-2.skp (a zip). All UVs are box-projected (metres / tile size).
Usage: tools_scene2_rebuild.py <Scene-2_structure.stl> <Scene-2.skp> <out_dir> <world.sdf>
Writes <out_dir>/{<part>.obj, env_*.obj, parts.mtl, parts.json, textures/} and replaces the
generated block of <world.sdf> (between the BEGIN/END generated markers)."""
import json, os, re, struct, sys, zipfile
from collections import defaultdict
import numpy as np

stl, skp, out, world = sys.argv[1:5]
os.makedirs(os.path.join(out, "textures"), exist_ok=True)

DECK_Z, LAND_Z, WATER_Z, BED_Z = 10.55, 0.6, 0.0, -1.0
X0, X1 = -9.2, -0.4                # deck edges
SIDE = 1.5                         # embankment / bank side slope (h:v)
EXT = 400.0                        # land/water extent beyond the bridge
FLAT, RAMP = 40.0, 100.0           # approach: level run past the deck end, then ramp run
GIRDERS = [(-8.5, -7.9), (-6.24, -5.64), (-3.97, -3.37), (-1.7, -1.1)]   # flange x-ranges

LABELS = {"deck": 1, "girder": 2, "cross_beam": 3, "pier_cap": 4, "pier_column": 5, "footing": 6,
          "abutment": 7, "railing": 8, "bearing": 9, "arch_truss": 10, "bridge_misc": 11,
          "terrain": 20, "water": 21, "vegetation": 22, "vehicle": 23, "road": 24, "other": 25}

KD = {"Grass": "0.78 0.82 0.72", "Water": "0.55 0.68 0.78", "Marking": "0.92 0.92 0.88"}
TEX = {  # material -> (path in .skp or None, tile metres (u, v), Ks)
    "Asphalt":  ("materials/[Asphalt_New]9/b75737cbab42b2679cb1dd6028e2b863.jpg", (3, 3), 0.05),
    "Concrete": ("materials/[Concrete_Form_4x8]6/2c81869e39432fab4dcf7675281e7f05.jpg", (1.22, 2.44), 0.08),
    "Grass":    ("materials/[Grass Dark Green]/b5d752ab9ef0faf28e067b4b316d0641.jpg", (6, 6), 0.02),
    "Bank":     ("materials/[Granite Dark Gray]/ca2b917262a44a734b7b3e8b902217c7.jpg", (2, 2), 0.05),
    "Water":    ("materials/[Water Dark Blue]/c82c93ce2baad2df7ffbfc33fe0e181a.jpg", (24, 14), 0.6),
    "Marking":  (None, (1, 1), 0.1),
}
z = zipfile.ZipFile(skp)
for m, (p, _, _) in TEX.items():
    if p:
        open(os.path.join(out, "textures", m + ".jpg"), "wb").write(z.read(p))


class Mesh:
    def __init__(self):
        self.V, self.VT, self.VN, self.F = [], [], [], defaultdict(list)

    def tri(self, mat, pts):
        """Polygon (planar, CCW seen from outside) with box-projected UVs."""
        pts = [np.asarray(p, float) for p in pts]
        n = np.cross(pts[1] - pts[0], pts[2] - pts[0])
        if np.linalg.norm(n) < 1e-12:
            return
        n /= np.linalg.norm(n)
        ax = int(np.argmax(np.abs(n)))
        tu, tv = TEX[mat][1]
        self.VN.append(tuple(n)); ni = len(self.VN)
        face = []
        for p in pts:
            u, v = [(p[1], p[2]), (p[0], p[2]), (p[0], p[1])][ax]
            self.V.append(tuple(p)); self.VT.append((u / tu, v / tv))
            face.append(len(self.V))
        self.F[mat].append([(i, i, ni) for i in face])

    def quad(self, mat, a, b, c, d):
        self.tri(mat, [a, b, c, d])

    def bbox(self):
        P = np.array(self.V)
        return P.min(0), P.max(0), P.mean(0)

    def ntris(self):
        return sum(len(f) - 2 for fl in self.F.values() for f in fl)

    def write(self, path):
        with open(path, "w") as o:
            o.write("# generated by tools_scene2_rebuild.py, Z-up metres\nmtllib parts.mtl\n")
            o.writelines(f"v {x:.4f} {y:.4f} {zz:.4f}\n" for x, y, zz in self.V)
            o.writelines(f"vt {u:.5f} {v:.5f}\n" for u, v in self.VT)
            o.writelines(f"vn {x:.4f} {y:.4f} {zz:.4f}\n" for x, y, zz in self.VN)
            for m, fl in self.F.items():
                o.write(f"g {m}\nusemtl {m}\n")
                for f in fl:
                    o.write("f " + " ".join(f"{v}/{t}/{n}" for v, t, n in f) + "\n")


# ---- bridge: classify triangles -----------------------------------------------------
b = open(stl, "rb").read()
n = struct.unpack("<I", b[80:84])[0]
T = np.frombuffer(b[84:84 + 50 * n], dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]))["v"].astype(float) / 1000.0
NRM = np.cross(T[:, 1] - T[:, 0], T[:, 2] - T[:, 0]); AREA = np.linalg.norm(NRM, axis=1) / 2
NRM /= 2 * AREA[:, None] + 1e-12
LO, HI, C = T.min(1), T.max(1), T.mean(1)


def in_girder(i):
    return any(LO[i, 0] >= a - 0.02 and HI[i, 0] <= b + 0.02 for a, b in GIRDERS)


def classify(i):
    zl, zh, cy = LO[i, 2], HI[i, 2], C[i, 1]
    span = 2.4 < cy < 92.6                       # between the abutment seats
    if zl >= 10.6 and zh <= 10.64:
        return "deck", "Marking"                  # lane markings
    if zh > 10.7:
        return "railing", "Concrete"              # parapets 10.55..11.48
    if zl >= 10.2:
        up = NRM[i, 2] > 0.9 and abs(C[i, 2] - DECK_Z) < 0.05
        return "deck", "Asphalt" if up else "Concrete"
    if span and zl >= 8.24 and zh <= 10.3 and in_girder(i):
        return "girder", "Concrete"
    if span and zl >= 8.149 and zh <= 8.26 and in_girder(i) and AREA[i] < 0.2:
        return "bearing", "Concrete"
    if cy < 5.4 or cy > 89.6:
        return ("footing" if zh <= 1.16 else "abutment"), "Concrete"
    if zl >= 7.0 and zh <= 8.21:
        return "pier_cap", "Concrete"
    if zh <= 0.16:
        return "footing", "Concrete"
    return "pier_column", "Concrete"


CLS = [classify(i) for i in range(len(T))]


def components(idx):
    """Connected components (welded at 2 mm) of the triangles idx."""
    P = T[idx].reshape(-1, 3)
    _, inv = np.unique(np.round(P / 0.002).astype(np.int64), axis=0, return_inverse=True)
    inv = inv.reshape(-1, 3); par = np.arange(inv.max() + 1)

    def find(a):
        r = a
        while par[r] != r:
            r = par[r]
        while par[a] != r:
            par[a], a = r, par[a]
        return r
    for t in inv:
        r = find(t[0])
        for v in t[1:]:
            par[find(v)] = r
    return np.unique([find(t[0]) for t in inv], return_inverse=True)[1]


parts = {}       # name -> (class, Mesh)
by_cls = defaultdict(list)
for i, (k, _) in enumerate(CLS):
    by_cls[k].append(i)
for k, idx in by_cls.items():
    idx = np.array(idx)
    cid = np.zeros(len(idx), int) if k == "deck" else components(idx)   # deck + markings = one part
    groups = [idx[cid == j] for j in range(cid.max() + 1)]
    groups.sort(key=lambda g: (round(C[g, 1].mean() / 4), C[g, 0].mean()))   # along +Y, then west->east
    for j, g in enumerate(groups, 1):
        m = Mesh()
        for i in g:
            m.tri(CLS[i][1], list(T[i]))
        parts[f"{k}_{j:02d}"] = (k, m)

# the SketchUp deck is open over both abutments (only the 0.3 m edge strips exist between the
# deck ends and the end railings), which leaves a hole you can see through: close the slab there
DECK_HOLES = [(-8.9, -0.72, -6.03, 1.88, -1), (-8.9, -0.72, 93.08, 100.98, +1)]   # x0 x1 y0 y1, deck end side
deck = parts["deck_01"][1]
for hx0, hx1, hy0, hy1, side in DECK_HOLES:
    zt, zb = DECK_Z, 10.25
    deck.quad("Asphalt", (hx0, hy0, zt), (hx1, hy0, zt), (hx1, hy1, zt), (hx0, hy1, zt))
    deck.quad("Concrete", (hx0, hy0, zb), (hx0, hy1, zb), (hx1, hy1, zb), (hx1, hy0, zb))
    ye = hy0 if side < 0 else hy1                         # end face at the deck end
    end = [(hx0, ye, zb), (hx1, ye, zb), (hx1, ye, zt), (hx0, ye, zt)]
    deck.quad("Concrete", *(end if side < 0 else end[::-1]))

# abutment back walls (river-side end of the approach fill): wall faces facing away from the river
backs = {}
for name, (k, m) in parts.items():
    if k != "abutment":
        continue
    lo, hi, c = m.bbox()
    idx = [i for i in by_cls["abutment"] if lo[1] - 0.01 <= C[i, 1] <= hi[1] + 0.01]
    ys = sorted({round(C[i, 1], 2) for i in idx if abs(NRM[i, 1]) > 0.9 and AREA[i] > 5 and LO[i, 2] >= 1.1})
    south = c[1] < 47.5
    backs[name] = (ys[0] if south else ys[-1], lo[1] if south else hi[1], -1 if south else 1)
    print(f"{name}: back wall y={backs[name][0]}, deck end y={backs[name][1]:.2f}, footing")

foot = {k: parts[k][1].bbox() for k in parts if k.startswith("footing")}
SHORE_S = max(hi[1] for lo, hi, _ in foot.values() if hi[1] < 10)     # river edge of abutment footings
SHORE_N = min(lo[1] for lo, hi, _ in foot.values() if lo[1] > 85)
print(f"banks start at y={SHORE_S:.2f} / {SHORE_N:.2f}")

# ---- environment --------------------------------------------------------------------
terrain, road, water = Mesh(), Mesh(), Mesh()
xa, xb = X0 - EXT, X1 + EXT
BANK_RUN = SIDE * (LAND_Z - BED_Z)
terrain.quad("Grass", (xa, SHORE_S - EXT, LAND_Z), (xb, SHORE_S - EXT, LAND_Z), (xb, SHORE_S, LAND_Z), (xa, SHORE_S, LAND_Z))
terrain.quad("Grass", (xa, SHORE_N, LAND_Z), (xb, SHORE_N, LAND_Z), (xb, SHORE_N + EXT, LAND_Z), (xa, SHORE_N + EXT, LAND_Z))
terrain.quad("Bank", (xa, SHORE_S, LAND_Z), (xb, SHORE_S, LAND_Z), (xb, SHORE_S + BANK_RUN, BED_Z), (xa, SHORE_S + BANK_RUN, BED_Z))
terrain.quad("Bank", (xa, SHORE_N - BANK_RUN, BED_Z), (xb, SHORE_N - BANK_RUN, BED_Z), (xb, SHORE_N, LAND_Z), (xa, SHORE_N, LAND_Z))
terrain.quad("Bank", (xa, SHORE_S + BANK_RUN, BED_Z), (xb, SHORE_S + BANK_RUN, BED_Z), (xb, SHORE_N - BANK_RUN, BED_Z), (xa, SHORE_N - BANK_RUN, BED_Z))
water.quad("Water", (xa, SHORE_S, WATER_Z), (xb, SHORE_S, WATER_Z), (xb, SHORE_N, WATER_Z), (xa, SHORE_N, WATER_Z))


def approach(abut, y_back, y_end, sign):
    """Road embankment filled from the abutment back wall outward (sign -1 south, +1 north).
    Under the deck overhang (y_back..y_end) the deck slab is the road, so no top there."""
    under = abs(y_end - y_back)
    ds = [0, under, under + FLAT] + [under + FLAT + RAMP * k / 10 for k in range(1, 11)]
    secs = []
    for d in ds:
        h = DECK_Z - (0 if d <= under + FLAT else (DECK_Z - LAND_Z) * (d - under - FLAT) / RAMP)
        w = SIDE * (h - LAND_Z)
        y = y_back + sign * d
        secs.append([(X0 - w, y, LAND_Z), (X0, y, h), (X1, y, h), (X1 + w, y, LAND_Z)])
    for s, (s0, s1) in enumerate(zip(secs, secs[1:])):
        a, c = (s0, s1) if sign < 0 else (s1, s0)        # keep faces CCW from outside
        terrain.quad("Grass", a[0], c[0], c[1], a[1])
        if s > 0:
            road.quad("Asphalt", a[1], c[1], c[2], a[2])
        terrain.quad("Grass", a[2], c[2], c[3], a[3])
    e = secs[0]                                          # wingwall face toward the river
    abut.tri("Concrete", [e[0], e[1], e[2], e[3]] if sign < 0 else [e[3], e[2], e[1], e[0]])


for name, (yb, ye, sign) in backs.items():
    approach(parts[name][1], yb, ye, sign)

# ---- write --------------------------------------------------------------------------
for f in os.listdir(out):
    if f.endswith(".obj"):
        os.remove(os.path.join(out, f))
with open(os.path.join(out, "parts.mtl"), "w") as o:
    for m, (p, _, ks) in TEX.items():
        o.write(f"newmtl {m}\nKa 0 0 0\nKd {KD.get(m, '1 1 1')}\nKs {ks} {ks} {ks}\nNs 20\n")
        o.write(f"map_Kd textures/{m}.jpg\n\n" if p else "\n")

meta, counts = [], defaultdict(int)
for name, (k, m) in sorted(parts.items()):
    m.write(os.path.join(out, name + ".obj"))
    lo, hi, c = m.bbox(); counts[k] += 1
    meta.append({"name": name, "class": k, "label": LABELS[k], "centroid": [round(float(v), 3) for v in (lo + hi) / 2],
                 "bbox_min": [round(float(v), 3) for v in lo], "bbox_max": [round(float(v), 3) for v in hi], "tris": m.ntris()})
env = {"env_terrain": ("terrain", terrain, True), "env_road": ("road", road, True), "env_water": ("water", water, False)}
for name, (k, m, _) in env.items():
    m.write(os.path.join(out, name + ".obj"))
    lo, hi, c = m.bbox()
    meta.append({"name": name, "class": k, "label": LABELS[k], "centroid": [round(float(v), 3) for v in (lo + hi) / 2],
                 "bbox_min": [round(float(v), 3) for v in lo], "bbox_max": [round(float(v), 3) for v in hi], "tris": m.ntris()})
json.dump({"scene": "scene2", "frame": "world ENU, metres", "labels": LABELS, "parts": meta},
          open(os.path.join(out, "parts.json"), "w"), indent=1)
print(dict(counts), "total", sum(counts.values()))

# ---- world SDF ----------------------------------------------------------------------
rel = os.path.basename(os.path.normpath(out))


def label(k):
    return f'<plugin filename="gz-sim-label-system" name="gz::sim::systems::Label"><label>{LABELS[k]}</label></plugin>'


L = ["    <!-- BEGIN generated by tools_scene2_rebuild.py: one link per bridge component, labelled per",
     "         BRIDGE_PARTS_SPEC.md; ground truth in scene2_parts/parts.json -->",
     '    <model name="scene2_bridge">', "      <static>true</static>"]
for name, (k, _) in sorted(parts.items()):
    uri = f"model://{rel}/{name}.obj"
    L.append(f'      <link name="{name}">'
             f'<visual name="visual"><geometry><mesh><uri>{uri}</uri></mesh></geometry>{label(k)}</visual>'
             f'<collision name="collision"><geometry><mesh><uri>{uri}</uri></mesh></geometry></collision></link>')
L.append("    </model>")
for name, (k, _, coll) in env.items():
    uri = f"model://{rel}/{name}.obj"
    L += [f'    <model name="scene2_{k}">', "      <static>true</static>", '      <link name="link">',
          f'        <visual name="visual">{"" if coll else "<cast_shadows>false</cast_shadows>"}'
          f'<geometry><mesh><uri>{uri}</uri></mesh></geometry>{label(k)}</visual>']
    if coll:
        L.append(f'        <collision name="collision"><geometry><mesh><uri>{uri}</uri></mesh></geometry></collision>')
    L += ["      </link>", "    </model>"]
L.append("    <!-- END generated -->")
s = open(world).read()
s, nsub = re.subn(r"    <!-- BEGIN generated.*?<!-- END generated -->", lambda _: "\n".join(L), s, flags=re.S)
if not nsub:
    raise SystemExit("world has no BEGIN/END generated block")
open(world, "w").write(s)
print("updated", world)
